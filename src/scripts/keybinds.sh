#!/usr/bin/env bash
# Apply custom keybinds stored in Serpantinum settings to Hyprland.
#
# Usage: keybinds.sh [sync]
#
# Custom shortcuts are kept in settings.json so they survive config updates and
# are written to a generated Lua file that keybinds.lua loads on every reload.

set -u

config_home="${XDG_CONFIG_HOME:-$HOME/.config}"
settings_file="$config_home/serpantinum/settings.json"
custom_file="$config_home/hypr/config/keybinds_custom.lua"

custom_json="[]"
removed_json="[]"
if [ -f "$settings_file" ] && command -v jq >/dev/null 2>&1; then
    custom_json="$(jq -c '.keybinds.custom // []' "$settings_file" 2>/dev/null)"
    removed_json="$(jq -c '.keybinds.removed // []' "$settings_file" 2>/dev/null)"
fi
[ -n "$custom_json" ] || custom_json="[]"
[ -n "$removed_json" ] || removed_json="[]"

mkdir -p "$(dirname "$custom_file")" 2>/dev/null

{
    echo "-- Generated by Serpantinum. Edit shortcuts in Settings > Keybinds."
    printf '%s' "$removed_json" | jq -r '
        .[] |
        (if type == "object" then .key else . end) as $combo |
        select($combo != null and $combo != "") |
        "pcall(function() hl.unbind(" + ($combo | tojson) + ") end)"
    ' 2>/dev/null
    printf '%s' "$custom_json" | jq -r '
        .[] |
        "pcall(function() hl.bind(" + (.key | tojson) +
        ", hl.dsp.exec_cmd(" + (.command | tojson) +
        "), { description = " + ((.description // "") | tojson) + " }) end)"
    ' 2>/dev/null
} > "$custom_file"

if command -v hyprctl >/dev/null 2>&1 && [ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]; then
    hyprctl reload >/dev/null 2>&1 || true
fi

exit 0
